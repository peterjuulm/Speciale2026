#!/usr/bin/env python3
"""Every entry that differs between one layer of two OCI files, by the Debian
package that owns it (23 November 2026).

    layer-owners.py A.oci.tar A-LAYER B.oci.tar B-LAYER

Compares each entry's type, mode, owner, mtime, size and content. Owners come
from var/lib/dpkg/info/*.list on either side (dpkg's own bookkeeping under
var/lib/dpkg/ is counted as "dpkg"). Prints the count of differing entries
per owner, and the entries that no package owns.
"""
import collections, gzip, hashlib, io, sys, tarfile

def layer(path, d):
    t = tarfile.open(path)
    lay = tarfile.open(fileobj=io.BytesIO(gzip.decompress(t.extractfile("blobs/sha256/" + d).read())))
    out, lists = {}, {}
    for m in lay:
        h = hashlib.sha256(lay.extractfile(m).read()).hexdigest() if m.isfile() else m.linkname
        out[m.name] = (m.type, m.mode, m.uid, m.gid, m.mtime, m.size, h)
        if m.name.startswith("var/lib/dpkg/info/") and m.name.endswith(".list"):
            pkg = m.name[len("var/lib/dpkg/info/"):-5]
            for line in lay.extractfile(m).read().decode().splitlines():
                lists[line.lstrip("/")] = pkg
    return out, lists

a, la = layer(sys.argv[1], sys.argv[2])
b, lb = layer(sys.argv[3], sys.argv[4])
owner = {**la, **lb}
count, unowned = collections.Counter(), []
for name in sorted(set(a) | set(b)):
    if a.get(name) == b.get(name):
        continue
    if name.startswith("var/lib/dpkg/") or name.startswith("var/cache/debconf/"):
        o = "dpkg/debconf bookkeeping"
    elif name in owner:
        o = owner[name]
    elif name.startswith("etc/ssl/certs/"):
        o = "ca-certificates (generated by update-ca-certificates)"
    else:
        o = None
    if o is None:
        unowned.append(name)
    else:
        count[o] += 1
print(f"entries: A {len(a)}, B {len(b)}; differing {sum(count.values()) + len(unowned)}")
for o, n in sorted(count.items()):
    print(f"  {n:4d}  {o}")
print(f"  {len(unowned):4d}  no package: {unowned}")
